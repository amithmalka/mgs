"""**כמה זמן באמת אין משיכה בדוט-קום — ולא כמה זמן לוקח לחזור לשיא.**

**הטעות שזה בא לתקן.** אמרתי ״נאסד״ק לקח 15.6 שנים לחזור לשיא, ולכן
הכלל היה חוסם משיכות שנים״. **הגרירה הזאת שגויה.**

כלל המשיכה אינו שואל ״האם חזרנו לשיא״. הוא שואל **״האם המחיר מעל
מחיר הקנייה הממוצע שלי״** — ו**הממוצע הזה יורד כל חודש**, כי המנגנון
ממשיך לקנות בדרך למטה. אחרי מפולת ארוכה הממוצע מתכנס אל המחירים
הנמוכים, **והרכיב נעשה זכאי הרבה לפני שהמדד חזר לשיא.**

**והמדידה על 2008 כבר רמזה על זה:** ‏S&P ירד 51% ולקח לו 37 חודשים
לחזור לשיא — **אבל החסימה הארוכה ביותר שנמדדה הייתה 22 חודשים.**
הפער הוא בדיוק הירידה של העלות הממוצעת.

⚠️ **ומה שכאן אינו מדידה.** אין לי סדרת 2000–2002 — שני הספקים
חסומים ב-240 נקודות חודשיות. לכן המסלול כאן **משוחזר משתי נקודות
עיגון שמתועדות בפרויקט** (`decks/combos.ts:118`): ירידה של 83%
לתחתית, וחזרה לשיא אחרי 15.6 שנים. הצורה שביניהן מונחת, ולכן
**המספר שיוצא הוא סדר גודל ולא מדידה.**
"""
DEP = 1000.0


def path(depth, months_down, years_back, tail=24, pre=36, pre_rise=0.10):
    """מסלול מחיר חודשי.

    **`pre` הוא התיקון שבלעדיו המבחן שקרי.** בגרסה הראשונה הצבירה
    קרתה **תוך כדי** המפולת, ולכן העלות הממוצעת נבנתה על מחירי
    תחתית ולא נחסם אף חודש — ובדיקת השפיות על 2008 החזירה 0 מול
    22 שנמדדו באמת. בפועל הצבירה קורית **לפני** המפולת ובמחירים
    גבוהים, ו-`pre` מוסיף בדיוק את זה: שנות עלייה לפני הקריסה.
    """
    out = []
    for i in range(pre):
        out.append(100.0 / (1 + pre_rise) ** ((pre - i) / 12))
    out.append(100.0)
    low = 100.0 * (1 - depth)
    for i in range(1, months_down + 1):
        out.append(100.0 * (low / 100.0) ** (i / months_down))
    up = int(years_back * 12) - months_down
    for i in range(1, up + 1):
        out.append(low * (100.0 / low) ** (i / up))
    for _ in range(tail):
        out.append(out[-1] * 1.006)
    return out


def blocked(px, start_at=0):
    """קונים כל חודש ומושכים מ-`start_at`. מחזיר (רצף חסימה ארוך, סה״כ)."""
    u = c = 0.0
    run = mx = tot = 0
    first_ok = None
    for i, p in enumerate(px):
        u += DEP / p; c += DEP
        if i < start_at:
            continue
        if p > c / u:
            if first_ok is None: first_ok = i
            run = 0
        else:
            run += 1; tot += 1; mx = max(mx, run)
    return mx, tot, first_ok


