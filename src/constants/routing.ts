/** MGS · לחלק על הכל לפי מנגנון הקנייה, או לבחור כמה?
 *
 *  נמדד על **הפקדות חודשיות אמיתיות** (IRR), לא על תשואת מדד.
 *
 *  **המבחן הכן — מחוץ למדגם.** בוחרים תמהיל על המחצית הראשונה של
 *  התקופה, **בלי לראות את ההמשך**, ובודקים אותו על המחצית השנייה.
 *  בלי זה כל השוואה מרמה את עצמה: תמהיל שנבחר אחרי שראינו מה עבד
 *  ינצח תמיד.
 *
 *  **התוצאה: הבחירה ניצחה בכל שלושת החלונות.** ובכל שלושתם המנגנון
 *  על יוניברס רחב היה גרוע — לעיתים גרוע מחלוקה שווה פשוטה.
 *
 *  **הסיבה:** המנגנון מנתב לנופל העמוק ביותר, ואינו מבחין בין ירידה
 *  זמנית לקריסה מתמשכת. ביוניברס רחב תמיד יש נכס שבור, והוא בולע
 *  את הכסף. בהרצה על 24 קרנות, רכיב אחד בלע **37% מכל ההפקדות**.
 *
 *  אין בזה המלצה ואין בזה ייעוץ פיננסי.
 */
export interface RoutingTest {
  months: number; train: string; test: string;
  /** המנגנון על כל הקרנות */ ruleAll: number;
  /** חלוקה שווה על כל הקרנות */ equalAll: number;
  /** התמהיל שנבחר על תקופת האימון, משקלות קבועים */ picked: number;
  /** המנגנון על אותו תמהיל */ rulePicked: number;
}

