/** הניכוי של העצמאי **נשחק** לפי המשכורת הקובעת כשכיר.
 *
 *  **מה שאומת ומה שלא — חשוב להבחין:**
 *
 *  · **הנוסחה עצמה היא קונצנזוס מקצועי מוחלט** (חשבים, כל-זכות):
 *    ההכנסה הקובעת היא הנמוך מבין ההכנסה מעסק לבין
 *    293,397₪ **בניכוי המשכורת שעליה הופקד לקרן**.
 *  · **אבל חיפוש בנוסח סעיף 17(5א) לא איתר את כלל ההפחתה.**
 *    ההגדרה שם פשוטה, בלי הפחתה. גם לא נמצא חוזר או תקנה
 *    שנושאים אותו.
 *
 *  **ולכן הנוסחה נשארת** — היא השמרנית, והיא מה שרואה חשבון
 *  ידווח בפועל. אבל היא **פרקטיקה ולא אסמכתא**, וזה נרשם כאן
 *  כדי שלא ייראה כאילו יש לה מקור חקוק שאותר.
 *
 *  **ותקרת הפטור ממס רווחי הון — אינה נשחקת.** גם לזה אין חוזר
 *  רשמי; הבסיס הוא ש-§9(16א) ו-§9(16ב) הן שתי הוראות פטור
 *  נפרדות שאין ביניהן הצלבה, ושתקנה 1(ב) לתקנות 1993 נדרשת
 *  במפורש כדי **למזג** חשבון שכיר וחשבון עצמאי — מה שמלמד
 *  שכברירת מחדל אלה שני חשבונות. */
export function selfDeduction(annualSalary: number): number {
  const remaining = Math.max(0, CEILINGS.selfIncome - Math.min(annualSalary, CEILINGS.empSalary));
  return Math.round(remaining * 0.045);
}

/** **שיעורי ההפקדה שהחוק קובע.**
 *  שכיר: 2.5% עובד ועוד 7.5% מעסיק = 10% מהמשכורת הקובעת.
 *  עצמאי: 7% מההכנסה הקובעת — 4.5% בניכוי ועוד 2.5% שאינם בניכוי
 *  אך פטורים ממס רווחי הון. */
export const RATE = { employee: 0.10, self: 0.07 } as const;

/** סך ההפקדה השנתית בהטבה מלאה — **התקרה המוחלטת**, למי שהכנסתו
 *  מגיעה לתקרת ההכנסה הקובעת. */
export function exemptCeiling(status: 'employee' | 'self' | 'both'): number {
  if (status === 'employee') return CEILINGS.empExempt;
  if (status === 'self') return CEILINGS.selfExempt;
  return CEILINGS.empExempt + CEILINGS.selfExempt;
}

/** **התקרה בפועל, לפי ההכנסה שהוזנה.**
 *
 *  הסכומים שבראש הקובץ הם התקרה למי שמרוויח את ההכנסה הקובעת
 *  המרבית. מי שמרוויח פחות **אינו רשאי להפקיד אותם** — ההפקדה
 *  המוטבת היא אחוז מהשכר, ורק הוא נחסם בתקרה:
 *
 *  · שכיר שמרוויח 8,000₪ לחודש — **800₪**, לא 1,571₪.
 *  · עצמאי שמרוויח 100,000₪ לשנה — **7,000₪**, לא 20,566₪.
 *
 *  הכנסה 0 פירושה ״לא הוזנה״, ואז מוחזרת התקרה המלאה כדי שהמסך
 *  לא יראה אפס לפני שמילאו כלום. */
export function ceilingFor(
  status: 'employee' | 'self' | 'both',
  annualSalary = 0, annualSelfIncome = 0,
): { year: number; capped: boolean } {
  /** **מי שהכנסתו מגיעה לתקרה הקובעת מקבל את הסכום שבחוק עצמו**,
   *  ולא את תוצאת הכפל. 7% מ-293,397₪ נותן 20,538₪ בעוד שהחוק נוקב
   *  ב-20,566₪ — הפרש של 28₪ שנובע מכך שהסכום נקבע בנפרד ומעוגל,
   *  ולא נגזר מהאחוז. לחשב אותו מהאחוז היה גורע מהמפקיד וגם מסמן
   *  אותו בטעות כ״מוגבל בהכנסה״. */
  const part = (income: number, incCeil: number, rate: number, full: number) =>
    income <= 0 || income >= incCeil ? full : Math.round(income * rate);

  const emp = status === 'employee' || status === 'both'
    ? part(annualSalary, CEILINGS.empSalary, RATE.employee, CEILINGS.empExempt) : 0;
  const slf = status === 'self' || status === 'both'
    ? part(annualSelfIncome, CEILINGS.selfIncome, RATE.self, CEILINGS.selfExempt) : 0;
  const year = emp + slf;
  return { year, capped: year < exemptCeiling(status) };
}

