/** ההנחה לתמהיל: ממוצע משוקלל של ההנחות לרכיביו, פחות דמי הניהול. */
export function forwardFor(
  parts: Array<{ k: string; w: number }>, outlook: Outlook = 'real',
): { cagr: number; gross: number; ter: number; sources: string[] } {
  const tot = parts.reduce((s, p) => s + p.w, 0);
  if (!tot) return { cagr: 0, gross: 0, ter: 0, sources: [] };
  let gross = 0, ter = 0;
  const srcs = new Set<string>();
  for (const p of parts) {
    const a = FORWARD[p.k];
    const f = IRISH.find(x => x.k === p.k);
    const w = p.w / tot;
    // ב״המשכיות״ נקודת הפתיחה היא מה שנמדד, לא ההנחה
    gross += w * (outlook === 'cont'
      ? Math.max(0, f?.cagr ?? a?.real ?? 0.075)
      : (a?.real ?? 0.075));
    ter += w * (f?.ter ?? 0.002);
    if (a) srcs.add(a.src);
  }
  gross = Math.max(0, gross + SHIFT[outlook]);
  return { cagr: Math.max(0, gross - ter), gross, ter, sources: [...srcs] };
}
