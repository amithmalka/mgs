export const bandFor = (childAge: number): KidBand =>
  KID_BANDS.find(b => childAge >= b.fromAge && childAge <= b.toAge) ?? KID_BANDS[2];

/** מס רווחי הון, משולם פעם אחת בסוף כי לא נמכר כלום בדרך */
export const KID_TAX = 0.25;

/** **מה הילד מקבל, בשלושה תרחישים ולא באחד.**
 *
 *  `median` היא ההערכה המרכזית; `p10` הוא התרחיש שאחד מעשרה חלונות
 *  בהיסטוריה הגיע אליו או גרוע ממנו; `worst` הוא **החלון הגרוע
 *  ביותר שנמדד בכלל** — לא אומדן, מקרה שקרה.
 */
export function projectKidBand(childAge: number, monthly: number): {
  band: KidBand; years: number; deposited: number;
  median: number; p10: number; worst: number;
  /** 4% בשנה מהסכום החציוני */
  monthlyIncome: number;
} {
  const band = bandFor(childAge);
  const years = Math.max(1, 20 - childAge);
  const net = (r: number) => {
    const m = Math.pow(1 + r, 1 / 12) - 1;
    let v = 0, c = 0;
    for (let i = 0; i < years * 12; i++) { v = (v + monthly) * (1 + m); c += monthly; }
    return v - Math.max(0, v - c) * KID_TAX;
  };
  const med = net(band.median);
  return {
    band, years, deposited: monthly * years * 12,
    median: med, p10: net(band.p10), worst: net(band.worst),
    monthlyIncome: med * 0.04 / 12,
  };
}
