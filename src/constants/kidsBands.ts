export interface KidBand {
  /** הגיל שבו הילד נמצא כשמתחילים */
  fromAge: number;
  toAge: number;
  label: string;
  mix: string;
  /** שמות המדדים ומשקלם — זה מה שנמדד, ולא שמות קרנות */
  parts: Array<{ idx: string; w: number }>;
  /** אופק ההשקעה שעליו נמדדו החלונות */
  horizon: number;
  /** מספר החלונות המתגלגלים שנמדדו */
  windows: number;
  /** **ההערכה המרכזית** — חציון כל החלונות */
  median: number;
  /** אחד מעשרה חלונות הסתיים כאן או נמוך מזה */
  p10: number;
  /** והחלון הגרוע ביותר שנמדד בכלל */
  worst: number;
  /** אחוז החלונות שהסתיימו בהפסד */
  negShare: number;
}

