/** **סינון נחיתות.** אם לתמהיל אחר יש תשואה שווה או גבוהה יותר
 *  **וגם** תנודתיות שווה או נמוכה יותר — אין טעם להציג את הנחות.
 *  השאלה ״מה ההבדל ביניהם״ ראויה לתשובה, ואם אין הבדל לטובה,
 *  התשובה היא שהתמהיל לא צריך להיות ברשימה. */
function undominated(list: Combo[]): Combo[] {
  return list.filter(a => !list.some(b =>
    b !== a && b.cagr >= a.cagr && b.vol <= a.vol &&
    (b.cagr > a.cagr || b.vol < a.vol)));
}

