/** **איך לתאר את הסיכון במילים, בלי לרכך אותו.**
 *
 *  `demo` הוא הסכום שעליו מדגימים, כדי שהנפילה תהיה מספר ולא אחוז.
 *  הנפילה המוצגת היא **המדודה בדולר** — העמוקה מהשתיים — ולצידה
 *  נאמר מה היא הייתה בשקל, וש**החלון אינו מכיל את 2008.** */
export function riskWords(c: Combo, demo: number) {
  const fall = Math.round(demo * -c.dd);
  const fallIls = Math.round(demo * -c.ddIls);
  const n = (v: number) => Math.round(v).toLocaleString('en-US');
  const top = c.parts[0];
  // **הזהב נמדד כגורם אחד.** GDX ו-SPGP הן שתיהן קרנות מכרות זהב,
  // וסכום המשקלים שלהן הוא החשיפה האמיתית לאותו סיכון עצמו.
  const gold = c.parts.filter(p => p.k === 'GDX' || p.k === 'SPGP')
                      .reduce((t, p) => t + p.w, 0);

  const fit = c.track === 'flow'
    ? 'מתאים למי שמושך כסף בדרך — התנודתיות כאן היא הנמוכה בקטלוג.'
    : c.track === 'both'
    ? 'מתאים למי שמושך מעט והיתרה ממשיכה לעבוד.'
    : 'מתאים לאופק ארוך בלי משיכה באמצע. עם משיכה בדרך, הנפילה נועלת הפסד.';

  return {
    dd: c.dd, ddIls: c.ddIls, w12: c.w12, fall, fallIls, gold,
    fit,
    drawdown: `הנפילה העמוקה שנמדדה: ${(c.dd * 100).toFixed(1)}% — על `
      + `${n(demo)}₪ זה ${n(fall)}₪. בשקל היא הייתה ${(c.ddIls * 100).toFixed(1)}%`
      + ` (${n(fallIls)}₪), כי הדולר מתחזק כשהשווקים יורדים.`,
    badYear: `השנה הגרועה בחלון: ${(c.w12 * 100).toFixed(1)}%. `
      + 'נמדד על 60 חודשים שבהם היה משבר אחד — אין בהם 2008 ואין '
      + '2000–2002, ולכן זו הגרועה שנמדדה, לא הגרועה שאפשרית.',
    concentration: gold >= 30
      ? `שימו לב: ${gold}% מהתמהיל הוא מכרות זהב — GDX ו-SPGP עוקבות `
        + 'אחרי אותו סקטור, וזו חשיפה אחת ולא שתיים. '
        + 'הזהב עלה לשיא בינואר 2026 וירד ממנו מאז.'
      : top.w >= 60
      ? `${top.w}% מהתמהיל יושב ב-${top.k} אחד.`
      : null,
    caveat: 'נמדד על 60 חודשים שבהם היה משבר אחד. אין בהם 2008 ואין'
      + ' 2000–2002 — הנפילה האפשרית עמוקה מזו.',
  };
}

