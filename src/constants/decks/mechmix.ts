const n0 = (v: number) => Math.round(v).toLocaleString('en-US');
/** **השם הקצר של הקרן.** השם המלא בקטלוג הוא ״טכנולוגיה S&P · Invesco
 *  swap״ — נכון, ובלתי קריא ככותרת עמודה. כאן נלקח רק החלק שלפני
 *  הנקודה, והסימול מופיע לידו פעם אחת בכותרת השקופית. */
const he = (k: string) => (IRISH.find(f => f.k === k)?.he ?? k).split(' · ')[0];

/** החלוקה בפועל לפי הכלל — אותה אריתמטיקה שב-`monthPlan` */
function split(
  parts: Array<{ k: string; w: number }>,
  track: 'flow' | 'both' | 'growth',
  falls: Record<string, number>,
  dep = 3000,
) {
  const w: Record<string, number> = {};
  for (const p of parts) w[p.k] = p.w / 100;
  const raw: Record<string, number> = {};
  let s = 0;
  for (const p of parts) {
    raw[p.k] = w[p.k] * (1 + DIP_TILT[track] * (falls[p.k] ?? 0) * 3);
    s += raw[p.k];
  }
  const out: Record<string, number> = {};
  for (const p of parts) out[p.k] = dep * raw[p.k] / s;
  let over = 0;
  for (const p of parts) {
    const cap = dep * w[p.k] * DIP_CAP;
    if (out[p.k] > cap) { over += out[p.k] - cap; out[p.k] = cap; }
  }
  if (over > 0) {
    const room = parts.map(p => Math.max(0, dep * w[p.k] * DIP_CAP - out[p.k]));
    const rs = room.reduce((a, b) => a + b, 0);
    if (rs > 0) parts.forEach((p, i) => { out[p.k] += over * room[i] / rs; });
  }
  return out;
}

/** שקופית שמראה תמהיל אחד בארבעה מצבי שוק */
function walkSlide(c: typeof COMBOS[number], id: string, eyebrow: string): Slide {
  const parts = c.parts.map(p => ({ k: p.k, w: p.w }));
  // הרכיב התנודתי ביותר בתמהיל הוא זה שנדגים עליו נפילה
  const hot = [...parts].sort((a, b) => a.w - b.w)[0];
  const cases: Array<[string, Record<string, number>]> = [
    ['כולם בשיא', {}],
    [`${he(hot.k)} ירד 20%`, { [hot.k]: 0.20 }],
    [`${he(hot.k)} ירד 50%`, { [hot.k]: 0.50 }],
    [`${he(hot.k)} ירד 80%`, { [hot.k]: 0.80 }],
  ];
  const head = ['מצב השוק', ...parts.map(p => `${he(p.k)}\n(יעד ${p.w}%)`)];
  const rows = cases.map(([lab, f]) => {
    const a = split(parts, c.track, f);
    return [lab, ...parts.map(p => `${n0(a[p.k])} ₪`)];
  });
  const cap = 3000 * (hot.w / 100) * DIP_CAP;
  return {
    id, eyebrow,
    title: `${parts.map(p => `${he(p.k)} ${p.w}%`).join(' · ')}  (${parts.map(p => p.k).join('/')})`,
    blocks: [
      { t: 'lede', text: '**הפקדה של 3,000 ₪, ואותו תמהיל בדיוק, בארבעה מצבי שוק.** '
        + 'שימו לב לשורה הראשונה: **כשאיש לא נפל, החלוקה שווה בדיוק לאחוזי התמהיל.**' },
      { t: 'table', head, rows },
      { t: 'good', text: `**ולמה זה לא בורח.** התקרה ל${he(hot.k)} היא **${n0(cap)} ₪** — `
        + `פי ${DIP_CAP} ממשקל היעד שלו. גם בנפילה של 80% הוא לא עובר אותה. `
        + `**ההטיה במסלול הזה היא ${DIP_TILT[c.track]}** — ככל שהאופק ארוך יותר, כך היא נדיבה יותר.` },
    ],
    src: 'DIP_TILT ו-DIP_CAP ב-monthPlan.ts · המשקלים מ-combos.ts.',
  };
}

