const TR_HE = { flow: 'תזרים', both: 'תזרים וצמיחה', growth: 'צמיחה' } as const;
const YEARS = { flow: [25, 25], both: [30, 20], growth: [35, 15] } as const;
const K = (n: number) => `${Math.round(n / 1000).toLocaleString('en-US')}K`;
const n0 = (n: number) => Math.round(n).toLocaleString('en-US');
const yr = (m: number) => (m / 12).toFixed(1);

/** שקופית אחת למסלול */
function trackSlide(tr: SimRow['tr']): Slide {
  const [dy, wy] = YEARS[tr];
  const rows = SIM.filter(r => r.tr === tr).sort((a, b) => b.i - a.i);
  return {
    id: `sim-${tr}`,
    eyebrow: `${dy} שנות הפקדה · ${wy} שנות משיכה`,
    title: `${TR_HE[tr]} — כל התמהילים, מקצה לקצה`,
    blocks: [
      { t: 'table',
        head: ['התמהיל', 'התיק בפרישה', 'משכורת ח׳', 'ואם לא יסתדר', 'סך ההכנסה', 'נפילה', 'נחסמו', 'ולכמה זמן'],
        rows: rows.map(r => [
          r.s, K(r.v), `${n0(r.a)} ₪`, `**${n0(r.a10)} ₪**`, K(r.i),
          `${(r.d * 100).toFixed(0)}%`,
          `${r.bl}%`,
          // **מתחת לעשרה מסלולים אין מה למדוד.** אורך הרצף הוא אז
          // המסלול הבודד שיצא במדגם, לא אומדן — ולכן לא מוצג מספר.
          r.nBl < 10 ? `מדגם קטן מדי (${r.nBl})` : `${yr(r.runMed)}–${yr(r.run90)} שנים`,
        ]),
        note: '**״ואם לא יסתדר״ היא אחוזון 10** — המשכורת בעשירית הגרועה של המסלולים. '
            + '**״ולכמה זמן״** הוא הרצף הרצוף הארוך ביותר בלי משכורת, בתוך המסלולים שנחסמו: '
            + 'מהחציון שלהם ועד האחוזון התשעים. **שורה שנחסמה בפחות מעשרה מסלולים מתוך 800 '
            + 'אינה מציגה מספר** — שם הזנב הוא מסלול בודד ולא אומדן.' },
    ],
    src: `800 מסלולי מחיר לכל שורה · תנודתיות ומתאמים מדודים · תשואה לפי ההנחות המפורסמות.`,
  };
}

